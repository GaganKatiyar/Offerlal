function product(s: RawSpec): Product {
  const id = `prod-${String(s.num).padStart(3, '0')}`;
  const sku = `OF-${s.skuPrefix}-${1000 + s.num}`;
  const sizes = s.sizes;
  const [imgA, imgB] = pickImages(s.imagePool, s.imageIndex);
  const images: ProductImage[] = [
    { id: `img-${s.num}-1`, url: pexelsImage(imgA, 1200), alt: `${s.name} - front view`, isPrimary: true },
    { id: `img-${s.num}-2`, url: pexelsImage(imgB, 1200), alt: `${s.name} - detail view` },
  ];
  const skus: ProductSku[] = sizes.map((size, i) => ({
    sku: `${sku}-${size.toUpperCase()}`,
    size,
    stock: size === 'Custom' ? 99 : ((s.num * 3 + i * 2) % 6) + (s.stockStatus === 'low-stock' ? 1 : 2),
  }));
  const isSareeLike = s.categoryId === 'cat-sarees';
  const isAccessoryLike = s.categoryId === 'cat-bridal-jewellery' || s.categoryId === 'cat-accessories';
  const care = isAccessoryLike ? ACCESSORY_CARE : isSareeLike ? SAREE_CARE : LEHENGA_CARE;

  return {
    id,
    slug: s.slug,
    name: s.name,
    sku,
    categoryId: s.categoryId,
    subCategory: s.subCategory,
    occasion: s.occasion,
    description: s.description,
    shortDescription: s.shortDescription,
    fabric: s.fabric,
    workDetails: s.workDetails,
    blouseDetails: s.blouseDetails,
    dupattaDetails: s.dupattaDetails,
    variants: [
      {
        id: `var-${s.num}-1`,
        color: s.color,
        colorHex: s.colorHex,
        images,
        skus,
      },
    ],
    sizes,
    price: s.price,
    compareAtPrice: s.compareAtPrice,
    currency: 'INR',
    rating: s.rating,
    reviewCount: s.reviewCount,
    stockStatus: s.stockStatus ?? 'in-stock',
    customizationOptions: withNum(s.customization, s.num),
    isBestseller: !!s.bestseller,
    isNewArrival: !!s.newArrival,
    isFeatured: !!s.featured,
    isBridal: !!s.bridal,
    careInstructions: care,
    deliveryEstimateDays: s.deliveryDays ?? (s.stockStatus === 'made-to-order' ? { standard: 12, express: 7 } : { standard: 6, express: 3 }),
    weightGrams: s.weightGrams,
    tags: s.tags,
    seo: {
      metaTitle: `${s.name} | Offerlal Fashion`,
      metaDescription: s.metaDescription,
      slug: s.slug,
      keywords: s.tags,
    },
    createdAt: s.createdAt,
    updatedAt: s.updatedAt ?? s.createdAt,
  };
}

